function callsOn(dayOffset: number, count: number, agentId: string, tool: string): ToolCall[] {
  const start = new Date()
  start.setHours(15, 0, 0, 0)
  start.setDate(start.getDate() - dayOffset)
  return Array.from({ length: count }, (_, index) => ({
    id: dayOffset * 20 + index + 1,
    agent_id: agentId,
    task_id: index % 2 === 0 ? "task-draft" : "task-done",
    tool,
    ok: index !== 3,
    duration_ms: 180 + index * 40,
    input_tokens: 800,
    output_tokens: 220,
    created_at: new Date(start.getTime() - index * minute).toISOString(),
  }))
}

